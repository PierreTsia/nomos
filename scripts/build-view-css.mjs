#!/usr/bin/env node
/**
 * Compile le CSS des vues MCP Apps (ADR 0022) : le raccord Tailwind du cœur + les
 * utilitaires que les composants emploient, sans aucune valeur de token. Le résultat est
 * écrit comme constante TypeScript committée (`src/mcp/view-css.generated.ts`, inlinée
 * dans chaque vue) **et** comme fichier CSS committé (`view.generated.css`, le sous-export
 * public `@nomosui/react/view.css`, ADR 0034). `--check` échoue s'il a dérivé — même régime
 * que `view.generated.ts` et `tokens.generated.css`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import tailwindcss from '@tailwindcss/postcss'
import postcss from 'postcss'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const DS = path.resolve(HERE, '..')
const INPUT = path.join(DS, 'src', 'mcp', 'view.css')
const TARGET = path.join(DS, 'src', 'mcp', 'view-css.generated.ts')
const CSS_TARGET = path.join(DS, 'view.generated.css')

const result = await postcss([tailwindcss()]).process(readFileSync(INPUT, 'utf8'), { from: INPUT })
const css = result.css

const header =
  '/**\n * Generated by scripts/build-view-css.mjs — do not edit by hand.\n * Replay: npm run build:view-css\n */\n'
const next = `${header}export const VIEW_CSS = ${JSON.stringify(css)}\n`

const cssHeader =
  '/* Generated by scripts/build-view-css.mjs — do not edit by hand. Replay: npm run build:view-css */\n'
const nextCss = `${cssHeader}${css}`

const read = (file) => {
  try {
    return readFileSync(file, 'utf8')
  } catch {
    return ''
  }
}

if (process.argv.includes('--check')) {
  const stale = read(TARGET) !== next || read(CSS_TARGET) !== nextCss
  if (stale) {
    console.error('view-css artefact is stale: replay `npm run build:view-css`.')
    process.exit(1)
  }
  console.log('up to date  src/mcp/view-css.generated.ts')
  console.log('up to date  view.generated.css')
} else {
  writeFileSync(TARGET, next, 'utf8')
  writeFileSync(CSS_TARGET, nextCss, 'utf8')
  console.log(`wrote   src/mcp/view-css.generated.ts + view.generated.css (${css.length} bytes)`)
}
